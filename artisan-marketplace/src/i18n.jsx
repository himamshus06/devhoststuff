const LanguageContext = createContext(null);
const STORAGE_KEY = "kayaka-language";

export function LanguageProvider({ children }) {
  const [language, setLanguage] = useState(() => {
    try {
      return localStorage.getItem(STORAGE_KEY) === "kn" ? "kn" : "en";
    } catch {
      return "en";
    }
  });

  useEffect(() => {
    document.documentElement.lang = language;
    try {
      localStorage.setItem(STORAGE_KEY, language);
    } catch {
      // Keep the selected language for this session if storage is unavailable.
    }
  }, [language]);

  const value = {
    language,
    toggleLanguage: () => setLanguage((current) => current === "en" ? "kn" : "en"),
    t: (text) => language === "kn" ? translations[text] || text : text,
  };

  return <LanguageContext.Provider value={value}>{children}</LanguageContext.Provider>;
}

export function useLanguage() {
  const context = useContext(LanguageContext);
  if (!context) throw new Error("useLanguage must be used inside LanguageProvider");
  return context;
}

export function LanguageToggle() {
  const { language, toggleLanguage } = useLanguage();
  return (
    <button className="language-toggle" type="button" onClick={toggleLanguage}
      aria-label={language === "en" ? "Switch to Kannada" : "Switch to English"}>
      {language === "en" ? "ಕನ್ನಡ" : "English"}
    </button>
  );
}
